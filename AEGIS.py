def planejamento_vistorias():
    cabecalho("Planejamento de vistorias", "Compare memoização e tabulação na seleção de ocorrências prioritárias "
              "conforme as horas disponíveis para atendimento.")
    conceito_aplicado(
        "MEMOIZAÇÃO (TOP-DOWN)",
        "O AEGIS seleciona ocorrências pendentes para aproveitar as horas de vistoria disponíveis "
        "e maximizar a pontuação de prioridade. A memoização usa uma função recursiva e "
        "armazena resultados intermediários para evitar cálculos repetidos."
    )
    conceito_aplicado(
        "TABULAÇÃO (BOTTOM-UP)",
        "O AEGIS resolve a seleção de vistorias preenchendo uma matriz de baixo para cima. "
        "Cada célula registra a melhor pontuação possível para uma quantidade de ocorrências "
        "e horas; o resultado pode ser comparado ao da memoização."
    )
    st.info("Planejamento demonstrativo: somente o gestor confirma equipes e datas no Centro de Operações.")
    pendentes = [o for o in dados["ocorrencias"] if o["status"] == "Pendente"]
    tabela_registros(pendentes, [("id", "Ocorrência"), ("bairro", "Bairro"),
                                 ("classificacao", "Prioridade"), ("horas", "Horas")])
    if not pendentes:
        return
    limite = st.slider("Horas disponíveis para o planejamento", 1, 20, 8)
    if st.button("Calcular e comparar os algoritmos", type="primary"):
        candidatos = backend.preparar_para_planejamento(pendentes)
        memo = backend.selecionar_vistorias_memo(candidatos, limite)
        tab = backend.selecionar_vistorias_tabela(candidatos, limite)
        col1, col2 = st.columns(2, gap="large")
        with col1:
            st.markdown("### Memoização · Top-Down")
            st.metric("Prioridade total", memo["pontos"])
            st.write("**Vistorias selecionadas:**", ", ".join(memo["ids"]) or "Nenhuma")
            st.write("**Horas utilizadas:**", memo["horas"])
            st.write("**Estados calculados:**", memo["estados"])
            st.write("**Resultados reutilizados:**", memo["reutilizacoes"])
        with col2:
            st.markdown("### Tabulação · Bottom-Up")
            st.metric("Prioridade total", tab["pontos"])
            st.write("**Vistorias selecionadas:**", ", ".join(tab["ids"]) or "Nenhuma")
            st.write("**Horas utilizadas:**", tab["horas"])
            st.write("**Células calculadas:**", tab["estados"])
        if memo["pontos"] == tab["pontos"]:
            st.success("As duas técnicas produziram o mesmo valor ótimo para esta capacidade.")
        else:
            st.error("Os resultados divergem; confira os dados antes de planejar.")
        with st.expander("Visualizar a matriz preenchida pela tabulação"):
            st.dataframe(pd.DataFrame(tab["tabela"]), width="stretch")
        st.caption("Complexidade temporal para ambas: O(n × H), "
                   "com n = vistorias candidatas e H = horas inteiras disponíveis. "
                   "Deslocamentos não estão incluídos nesta simulação.")


