def desenho_grafo(grafo, origem, destino, chave="grafo"):
    """Desenha um GRAFO interativo, não um mapa geográfico.

    NetworkX é usado somente para criar posições visuais estáveis dos nós.
    A busca de caminho é feita pela função BFS do backend, não pelo NetworkX.
    """
    caminho = backend.menor_caminho_bfs(grafo, origem, destino)
    rede = nx.Graph()
    for no, vizinhos in grafo.items():
        rede.add_node(no)
        for vizinho in vizinhos:
            rede.add_edge(no, vizinho)

    posicoes = nx.spring_layout(rede, seed=21, iterations=160, k=1.15)
    figura = go.Figure()
    x_arestas, y_arestas = [], []
    for a, b in rede.edges():
        x_arestas += [posicoes[a][0], posicoes[b][0], None]
        y_arestas += [posicoes[a][1], posicoes[b][1], None]
    figura.add_trace(go.Scatter(
        x=x_arestas, y=y_arestas, mode="lines",
        line=dict(width=2.3, color="#385369"), hoverinfo="skip",
        showlegend=False, name="Conexões"))

    if len(caminho) >= 2:
        x_caminho, y_caminho = [], []
        for a, b in zip(caminho, caminho[1:]):
            x_caminho += [posicoes[a][0], posicoes[b][0], None]
            y_caminho += [posicoes[a][1], posicoes[b][1], None]
        figura.add_trace(go.Scatter(
            x=x_caminho, y=y_caminho, mode="lines",
            line=dict(width=6, color="#4ce2bd"), hoverinfo="skip",
            showlegend=False, name="Menor caminho BFS"))

    nomes = list(rede.nodes())
    cores = []
    tamanhos = []
    for ponto in nomes:
        if ponto == origem and ponto == destino:
            cores.append("#70baff")
            tamanhos.append(36)
        elif ponto == origem:
            cores.append("#4ce2bd")
            tamanhos.append(35)
        elif ponto == destino:
            cores.append("#ffb56c")
            tamanhos.append(35)
        elif ponto in caminho:
            cores.append("#a3f6dd")
            tamanhos.append(29)
        else:
            cores.append("#294c64")
            tamanhos.append(23)

    figura.add_trace(go.Scatter(
        x=[posicoes[p][0] for p in nomes],
        y=[posicoes[p][1] for p in nomes],
        mode="markers+text", text=[n.replace(" ", "<br>", 1) if len(n) > 15 else n for n in nomes],
        textposition="top center", textfont=dict(color="#e8f5fa", size=11),
        marker=dict(size=tamanhos, color=cores, line=dict(color="#d7f9f0", width=1.1)),
        customdata=nomes, hovertemplate="<b>%{customdata}</b><extra></extra>",
        showlegend=False,
    ))
    figura.update_layout(
        height=570, margin=dict(l=12, r=12, t=30, b=5),
        paper_bgcolor="#0e1b2b", plot_bgcolor="#0e1b2b", font=dict(color="#e5f5fb"),
        xaxis=dict(visible=False, showgrid=False, zeroline=False, scaleanchor="y", scaleratio=1),
        yaxis=dict(visible=False, showgrid=False, zeroline=False),
        hoverlabel=dict(bgcolor="#173548", font_color="#ffffff"),
        dragmode="pan", clickmode="event+select",
    )
    st.plotly_chart(figura, width="stretch", config={"displayModeBar": True,
                    "modeBarButtonsToRemove": ["lasso2d", "select2d"], "scrollZoom": True},
                    key=f"plot_{chave}")
    st.caption("Origem: verde-claro | Destino: âmbar | Linha verde: caminho com menos conexões. "
               "Rede ilustrativa, sem distâncias ou coordenadas reais.")
    return caminho


